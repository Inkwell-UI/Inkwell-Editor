/** What the compiler knows about one scrollbar (overlay role `scrollbar`, Spec `scrollbar`); numbers are design px inside the bar frame. */
export interface ScrollbarInfo {
  /** Clip path from the root timeline of the bar frame, and of the list or scrolling frame it follows (the `root.` prefix is dropped). */
  path: string
  target: string
  /** Instance name of the thumb inside the bar frame. */
  thumb: string
  vertical: boolean
  /** The track box in the bar frame (the frame itself when it has no `track` child). */
  x: number
  y: number
  w: number
  h: number
}

export const scrollbarClassName = (modId: string): string => `mods.${modId}.InkwellScrollbar`

const q = (s: string): string => JSON.stringify(s)
const num = (n: number): string => String(Math.round(n * 1000) / 1000)

/** Frame code that attaches a scrollbar: must run after the list and scroll attach code, because it asks the target for its state. */
export const scrollbarAttachCode = (modId: string, s: ScrollbarInfo, root = 'this'): string =>
  `${scrollbarClassName(modId)}.attach(${root}, ${q(s.path)}, ${q(s.target)}, ${q(s.thumb)}, ${s.vertical}, ${[s.x, s.y, s.w, s.h].map(num).join(', ')});`

/**
 * The scrollbar (generated by Inkwell): the author draws the track and the thumb in Figma, this only moves and sizes the thumb along the track. It asks its target (a list or a scrolling
 * frame: `clip.barState(vertical)` = `{pos, max, view}`, `clip.barTo(vertical, pos)`) about 30 times a second, so it also follows items a graph adds later, and shows the bar only while
 * `max > 0` and the target is shown. Mouse: pressing the thumb drags it; pressing the track jumps the thumb there (centred on the click) and goes on dragging. The thumb is resized along the
 * bar (never below 16 px), so a rounded thumb stretches with it. shortcut: the bar's `_visible` is ours (a graph's Set Visible on a scrollbar is overridden when the target's state changes);
 * mouse only, a scrollbar is not a focus target; one wheel or key still moves the target, not the bar.
 */
export function scrollbarClassSource(modId: string): string {
  const me = scrollbarClassName(modId)
  return `// Generated by Inkwell: scrollbars (overlay role scrollbar). Do not edit.
class ${me} {
    static var bars;
    static var hooked;
    static var MIN = 16;
    var clip;
    var target;
    var thumb;
    var vertical;
    var x;
    var y;
    var w;
    var h;
    var len;
    var tl;
    var drag;
    var grab;
    var on;

    function InkwellScrollbar(clip, target, thumb, vertical, x, y, w, h) {
        this.clip = clip;
        this.target = target;
        this.thumb = thumb;
        this.vertical = vertical;
        this.x = x;
        this.y = y;
        this.w = w;
        this.h = h;
        this.len = vertical ? h : w;
        this.tl = this.len;
        this.drag = false;
    }

    // frame code: ${me}.attach(this, "path.to.bar", "path.to.target", "thumb", vertical, trackX, trackY, trackW, trackH)
    static function attach(root, path, targetPath, thumbName, vertical, x, y, w, h) {
        if (${me}.bars == undefined) ${me}.bars = [];
        var clip = root;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) clip = clip[a[k]];
        var target = root;
        var b = targetPath.split(".");
        for (var j = 0; j < b.length; j++) target = target[b[j]];
        var thumb = clip[thumbName];
        if (clip == undefined || target == undefined || thumb == undefined || typeof (target.barState) != "function") {
            trace("[Inkwell] scrollbar " + path + ": bar, thumb or target " + targetPath + " not found, or the target is not a list or scrolling frame");
            return;
        }
        for (var i = ${me}.bars.length - 1; i >= 0; i--) if (${me}.bars[i].clip == clip) ${me}.bars.splice(i, 1);
        var self = new ${me}(clip, target, thumb, vertical, x, y, w, h);
        ${me}.bars.push(self);
        self.update();
        ${me}.hook();
    }

    static function hook() {
        if (${me}.hooked == true) return;
        ${me}.hooked = true;
        var mouse = new Object();
        mouse.onMouseDown = function() {
            ${me}.press();
        };
        mouse.onMouseMove = function() {
            ${me}.move();
        };
        mouse.onMouseUp = function() {
            ${me}.release();
        };
        Mouse.addListener(mouse);
        setInterval(function() {
            ${me}.tick();
        }, 33);
    }

    static function tick() {
        for (var k = 0; k < ${me}.bars.length; k++) ${me}.bars[k].update();
    }

    static function press() {
        for (var k = ${me}.bars.length - 1; k >= 0; k--) if (${me}.bars[k].pressed()) return;
    }

    static function move() {
        for (var k = 0; k < ${me}.bars.length; k++) if (${me}.bars[k].drag) ${me}.bars[k].follow();
    }

    static function release() {
        for (var k = 0; k < ${me}.bars.length; k++) ${me}.bars[k].drag = false;
    }

    // the bar and the target are shown (every parent up to the root is visible, except the bar itself, which is ours)
    function shown() {
        var c = this.target;
        while (c != undefined && c != _root) {
            if (!c._visible) return false;
            c = c._parent;
        }
        c = this.clip._parent;
        while (c != undefined && c != _root) {
            if (!c._visible) return false;
            c = c._parent;
        }
        return true;
    }

    function update() {
        var s = this.target.barState(this.vertical);
        var show = s.max > 0 && this.shown();
        if (show != this.on) {
            this.on = show;
            this.clip._visible = show;
        }
        if (!show) {
            this.drag = false;
            return;
        }
        this.tl = Math.min(this.len, Math.max(${me}.MIN, this.len * s.view / (s.view + s.max)));
        var p = (this.len - this.tl) * Math.min(1, Math.max(0, s.pos / s.max));
        if (this.vertical) {
            this.thumb._height = this.tl;
            this.thumb._y = this.y + p;
        } else {
            this.thumb._width = this.tl;
            this.thumb._x = this.x + p;
        }
    }

    // a press on the thumb drags it; a press on the track jumps the thumb there (centred) and drags on from it
    function pressed() {
        if (!this.on) return false;
        var mx = this.clip._xmouse;
        var my = this.clip._ymouse;
        if (mx < this.x || my < this.y || mx > this.x + this.w || my > this.y + this.h) return false;
        var m = this.vertical ? my - this.y : mx - this.x;
        var t = this.vertical ? this.thumb._y - this.y : this.thumb._x - this.x;
        if (m >= t && m <= t + this.tl) this.grab = m - t;
        else this.grab = this.tl / 2;
        this.drag = true;
        this.follow();
        return true;
    }

    function follow() {
        var s = this.target.barState(this.vertical);
        var travel = this.len - this.tl;
        if (!(s.max > 0) || !(travel > 0)) return;
        var m = (this.vertical ? this.clip._ymouse - this.y : this.clip._xmouse - this.x) - this.grab;
        this.target.barTo(this.vertical, Math.min(1, Math.max(0, m / travel)) * s.max);
        this.update();
    }
}
`
}
