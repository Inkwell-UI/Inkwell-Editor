/** What the compiler knows about one list component (overlay role `list`, SPEC-CHANGES S8); all numbers are design px relative to the list frame. */
export interface ListInfo {
  /** Clip path from the root timeline, `a.b.list` (the `root.` prefix is dropped). */
  path: string
  /** Instance name of the item template inside the list frame. */
  template: string
  w: number
  h: number
  /** Template box in the list frame. */
  tx: number
  ty: number
  tw: number
  th: number
  spacing: number
  /** Text layers of the template in layer order: field name (instance name) and clip path relative to the template. */
  fields: { name: string; path: string }[]
}

export const listClassName = (modId: string): string => `mods.${modId}.InkwellList`

const q = (s: string): string => JSON.stringify(s)
const num = (n: number): string => String(Math.round(n * 1000) / 1000)

/** Frame code that turns a compiled frame into a list: runs before the menu class starts, so graphs can register events on it. */
export const listAttachCode = (modId: string, l: ListInfo, root = 'this'): string =>
  `${listClassName(modId)}.attach(${root}, ${q(l.path)}, ${q(l.template)}, ${[l.w, l.h, l.tx, l.ty, l.tw, l.th, l.spacing].map(num).join(', ')}, [${l.fields.map((f) => q(f.name)).join(', ')}], [${l.fields.map((f) => q(f.path)).join(', ')}]);`

/**
 * The basic list component (S8), generated by Inkwell: never CLIK or SkyUI. One class per mod; `attach` gives the frame clip the members the Core-Pack list nodes and
 * events expect (`setItems`, `refresh`, `getSelectedIndex`, `getItem`, `addEventListener`, `value`). Rows are copies of the hidden item template (only the visible rows
 * plus one exist and are recycled), the frame is clipped with a mask. Mouse wheel and keys come from AS2 listeners until the runtime forwards user events to
 * `input()` (then the key listener stops, so a key never moves the highlight twice). Events: `change` (clip.value = highlighted index), `itemClick` ({index, data}).
 */
export function listClassSource(modId: string): string {
  const me = listClassName(modId)
  return `// Generated by Inkwell: the basic list component (SPEC-CHANGES S8). Do not edit.
class ${me} {
    static var lists;
    static var active;
    static var hooked;
    static var runtimeInput;
    var clip;
    var tpl;
    var w;
    var h;
    var tx;
    var ty;
    var tw;
    var rowH;
    var spacing;
    var names;
    var paths;
    var items;
    var rows;
    var top;
    var hl;
    var full;
    var listeners;

    function InkwellList(clip, tpl, w, h, tx, ty, tw, th, spacing, names, paths) {
        this.clip = clip;
        this.tpl = tpl;
        this.w = w;
        this.h = h;
        this.tx = tx;
        this.ty = ty;
        this.tw = tw;
        this.spacing = spacing;
        this.rowH = th + spacing;
        if (!(this.rowH > 0)) this.rowH = 1;
        this.names = names;
        this.paths = paths;
        this.items = [];
        this.rows = [];
        this.top = 0;
        this.hl = -1;
        this.full = 1;
        this.listeners = [];
    }

    // frame code: ${me}.attach(this, "path.to.list", "template", w, h, tx, ty, tw, th, spacing, [field names], [field paths])
    static function attach(root, path, tplName, w, h, tx, ty, tw, th, spacing, names, paths) {
        if (${me}.lists == undefined) ${me}.lists = [];
        var clip = root;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) clip = clip[a[k]];
        var t = clip[tplName];
        if (clip == undefined || t == undefined) {
            trace("[Inkwell] list " + path + ": clip or item template " + tplName + " not found");
            return;
        }
        for (var j = ${me}.lists.length - 1; j >= 0; j--) if (${me}.lists[j].clip == clip) ${me}.lists.splice(j, 1);
        if (${me}.active.clip == clip) ${me}.active = undefined;
        var self = new ${me}(clip, t, w, h, tx, ty, tw, th, spacing, names, paths);
        t._visible = false;
        var m = clip.createEmptyMovieClip("listMask__", 9998);
        m.beginFill(0, 100);
        m.moveTo(0, 0);
        m.lineTo(w, 0);
        m.lineTo(w, h);
        m.lineTo(0, h);
        m.lineTo(0, 0);
        m.endFill();
        clip.setMask(m);
        clip.value = -1;
        clip.setItems = function(items) {
            self.setItems(items);
        };
        clip.refresh = function() {
            self.refresh();
        };
        clip.getSelectedIndex = function() {
            return self.hl;
        };
        clip.getItem = function(i) {
            return self.items[i];
        };
        clip.addEventListener = function(type, scope, method) {
            self.listeners.push({ type: type, scope: scope, method: method });
        };
        clip.removeEventListener = function(type, scope, method) {
            for (var k = self.listeners.length - 1; k >= 0; k--) {
                var l = self.listeners[k];
                if (l.type == type && l.scope == scope && l.method == method) self.listeners.splice(k, 1);
            }
        };
        ${me}.lists.push(self);
        ${me}.hook();
    }

    static function hook() {
        if (${me}.hooked == true) return;
        ${me}.hooked = true;
        var mouse = new Object();
        mouse.onMouseWheel = function(delta) {
            ${me}.wheel(delta);
        };
        Mouse.addListener(mouse);
        var keys = new Object();
        keys.onKeyDown = function() {
            ${me}.key(Key.getCode());
        };
        Key.addListener(keys);
    }

    static function pick() {
        return ${me}.active != undefined ? ${me}.active : ${me}.lists[0];
    }

    // mouse wheel over a list: up = highlight moves up
    static function wheel(delta) {
        for (var k = 0; k < ${me}.lists.length; k++) {
            var l = ${me}.lists[k];
            if (l.under()) {
                l.move(delta > 0 ? -1 : 1);
                return;
            }
        }
    }

    // AS2 key events: used until the runtime forwards user events (input)
    static function key(code) {
        if (${me}.runtimeInput == true) return;
        var l = ${me}.pick();
        if (code == 38) l.move(-1);
        else if (code == 40) l.move(1);
        else if (code == 33) l.move(-l.full);
        else if (code == 34) l.move(l.full);
        else if (code == 13) l.accept();
    }

    // the runtime's user events (S7 On Input actions), called by the menu class
    static function input(action) {
        ${me}.runtimeInput = true;
        var l = ${me}.pick();
        if (l == undefined) return;
        if (action == "Up") l.move(-1);
        else if (action == "Down") l.move(1);
        else if (action == "PageUp") l.move(-l.full);
        else if (action == "PageDown") l.move(l.full);
        else if (action == "Accept") l.accept();
    }

    function under() {
        var x = this.clip._xmouse;
        var y = this.clip._ymouse;
        return this.clip._visible && x >= 0 && y >= 0 && x <= this.w && y <= this.h;
    }

    function setItems(items) {
        this.items = items instanceof Array ? items : [];
        this.hl = -1;
        this.clip.value = -1;
        this.top = 0;
        this.refresh();
    }

    function move(d) {
        var n = this.items.length;
        if (n == 0) return;
        var i = this.hl < 0 ? (d > 0 ? d - 1 : 0) : this.hl + d;
        this.highlight(i);
    }

    function highlight(i) {
        var n = this.items.length;
        if (n == 0) return;
        if (i < 0) i = 0;
        if (i > n - 1) i = n - 1;
        var changed = i != this.hl;
        this.hl = i;
        this.clip.value = i;
        this.refresh();
        if (changed) this.fire("change", {});
    }

    function accept() {
        if (this.hl >= 0 && this.hl < this.items.length) this.fire("itemClick", { index: this.hl, data: this.items[this.hl] });
    }

    function click(i) {
        if (i < 0 || i >= this.items.length) return;
        ${me}.active = this;
        this.highlight(i);
        this.fire("itemClick", { index: i, data: this.items[i] });
    }

    function fire(type, e) {
        e.type = type;
        e.target = this.clip;
        var ls = this.listeners.slice();
        for (var k = 0; k < ls.length; k++) {
            var l = ls[k];
            if (l.type != type) continue;
            try {
                l.scope[l.method](e);
            } catch (x) {
                trace("[Inkwell] list " + type + ": " + x);
            }
        }
    }

    function field(row, path) {
        var o = row;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) o = o[a[k]];
        return o;
    }

    function fill(row, item) {
        if (typeof (item) == "object") {
            for (var k = 0; k < this.names.length; k++) {
                var v = item[this.names[k]];
                this.field(row, this.paths[k]).text = v == undefined ? "" : String(v);
            }
        } else if (this.paths.length > 0) {
            this.field(row, this.paths[0]).text = item == undefined ? "" : String(item);
        }
    }

    function makeRow(r) {
        var self = this;
        this.tpl.duplicateMovieClip("row" + r, 1000 + r);
        var row = this.clip["row" + r];
        var hit = row.createEmptyMovieClip("hit__", 9999);
        hit.beginFill(0, 0);
        hit.moveTo(0, 0);
        hit.lineTo(this.tw, 0);
        hit.lineTo(this.tw, this.rowH - this.spacing);
        hit.lineTo(0, this.rowH - this.spacing);
        hit.lineTo(0, 0);
        hit.endFill();
        row.onRelease = function() {
            self.click(this.itemIndex);
        };
        return row;
    }

    // redraws the rows from the current items: the visible rows plus one, recycled; the highlighted row is kept in view
    function refresh() {
        var n = this.items.length;
        this.full = Math.max(1, Math.floor((this.h + this.spacing) / this.rowH));
        if (this.hl >= 0) {
            if (this.hl < this.top) this.top = this.hl;
            if (this.hl >= this.top + this.full) this.top = this.hl - this.full + 1;
        }
        var maxTop = Math.max(0, n - this.full);
        if (this.top > maxTop) this.top = maxTop;
        if (this.top < 0) this.top = 0;
        var pool = Math.ceil(this.h / this.rowH) + 1;
        for (var r = 0; r < pool; r++) {
            var i = this.top + r;
            var row = this.rows[r];
            if (i >= n) {
                if (row != undefined) row._visible = false;
                continue;
            }
            if (row == undefined) {
                row = this.makeRow(r);
                this.rows[r] = row;
            }
            row._visible = true;
            row._x = this.tx;
            row._y = this.ty + r * this.rowH;
            row.itemIndex = i;
            row._alpha = i == this.hl ? 100 : 60;
            this.fill(row, this.items[i]);
        }
    }
}
`
}
