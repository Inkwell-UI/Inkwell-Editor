/** What the compiler knows about one list component (overlay role `list`, SPEC-CHANGES S8); all numbers are design px relative to the list frame. */
export interface ListInfo {
  /** Clip path from the root timeline, `a.b.list` (the `root.` prefix is dropped). */
  path: string
  /** Instance name of the item template inside the list frame. */
  template: string
  w: number
  h: number
  /** Template box in the list frame. */
  tx: number
  ty: number
  tw: number
  th: number
  spacing: number
  /** Text layers of the template in layer order: field name (instance name) and clip path relative to the template. */
  fields: { name: string; path: string }[]
}

export const listClassName = (modId: string): string => `mods.${modId}.InkwellList`

const q = (s: string): string => JSON.stringify(s)
const num = (n: number): string => String(Math.round(n * 1000) / 1000)

/** Frame code that turns a compiled frame into a list: runs before the menu class starts, so graphs can register events on it. */
export const listAttachCode = (modId: string, l: ListInfo, root = 'this'): string =>
  `${listClassName(modId)}.attach(${root}, ${q(l.path)}, ${q(l.template)}, ${[l.w, l.h, l.tx, l.ty, l.tw, l.th, l.spacing].map(num).join(', ')}, [${l.fields.map((f) => q(f.name)).join(', ')}], [${l.fields.map((f) => q(f.path)).join(', ')}]);`

/**
 * The basic list component (S8), generated by Inkwell: never CLIK or SkyUI. One class per mod; `attach` gives the frame clip the members the Core-Pack list nodes and
 * events expect (`setItems`, `refresh`, `getSelectedIndex`, `getItem`, `addEventListener`, `value`). Rows are copies of the hidden item template (only the visible rows
 * plus one exist and are recycled), the frame is clipped with a mask. Mouse wheel and keys come from AS2 listeners until the runtime forwards user events to
 * `input()` (then the key listener stops, so a key never moves the highlight twice). A list frame with no children is a component list: its items are Make Component recipes
 * (`{symbol, cls, size, props}`; Add to List, Set Items) and a row is that component, built with the item's props. shortcut: all rows share the first recipe's height (40 px without a size). Events: `change` (clip.value = highlighted index), `itemClick` ({index, data}).
 */
export function listClassSource(modId: string): string {
  const me = listClassName(modId)
  return `// Generated by Inkwell: the basic list component (SPEC-CHANGES S8). Do not edit.
class ${me} {
    static var lists;
    static var active;
    static var hooked;
    static var runtimeInput;
    static var gated;
    static var focusPath;
    var clip;
    var tpl;
    var w;
    var h;
    var tx;
    var ty;
    var tw;
    var rowH;
    var spacing;
    var names;
    var paths;
    var items;
    var rows;
    var top;
    var hl;
    var has;
    var lit;
    var hov;
    var full;
    var listeners;
    var comp;
    var owner;

    function InkwellList(clip, tpl, w, h, tx, ty, tw, th, spacing, names, paths) {
        this.clip = clip;
        this.tpl = tpl;
        this.w = w;
        this.h = h;
        this.tx = tx;
        this.ty = ty;
        this.tw = tw;
        this.spacing = spacing;
        this.rowH = th + spacing;
        if (!(this.rowH > 0)) this.rowH = 1;
        this.names = names;
        this.paths = paths;
        this.items = [];
        this.rows = [];
        this.top = 0;
        this.hl = -1;
        this.full = 1;
        this.listeners = [];
    }

    // frame code: ${me}.attach(this, "path.to.list", "template", w, h, tx, ty, tw, th, spacing, [field names], [field paths])
    static function attach(root, path, tplName, w, h, tx, ty, tw, th, spacing, names, paths) {
        if (${me}.lists == undefined) ${me}.lists = [];
        var clip = root;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) clip = clip[a[k]];
        var t = clip[tplName];
        if (clip == undefined || (tplName != "" && t == undefined)) {
            trace("[Inkwell] list " + path + ": clip or item template " + tplName + " not found");
            return;
        }
        for (var j = ${me}.lists.length - 1; j >= 0; j--) if (${me}.lists[j].clip == clip) ${me}.lists.splice(j, 1);
        if (${me}.active.clip == clip) ${me}.active = undefined;
        var self = new ${me}(clip, t, w, h, tx, ty, tw, th, spacing, names, paths);
        if (t != undefined) t._visible = false;
        self.comp = tplName == "";
        var m = clip.createEmptyMovieClip("listMask__", 9998);
        m.beginFill(0, 100);
        m.moveTo(0, 0);
        m.lineTo(w, 0);
        m.lineTo(w, h);
        m.lineTo(0, h);
        m.lineTo(0, 0);
        m.endFill();
        clip.setMask(m);
        if (self.comp) {
            // a row takes no mouse handler (it would swallow its component's events), so hover is found from the mouse position
            Mouse.removeListener(clip.hoverL__);
            clip.hoverL__ = { onMouseMove: function() { self.hover(); } };
            Mouse.addListener(clip.hoverL__);
        }
        clip.value = -1;
        clip.setItems = function(items, owner) {
            self.setItems(items, owner);
        };
        clip.addItem = function(item, owner) {
            self.addItem(item, owner);
        };
        clip.refresh = function() {
            self.refresh();
        };
        clip.getSelectedIndex = function() {
            return self.hl;
        };
        clip.getItem = function(i) {
            return self.items[i];
        };
        clip.addEventListener = function(type, scope, method) {
            self.listeners.push({ type: type, scope: scope, method: method });
        };
        clip.removeEventListener = function(type, scope, method) {
            for (var k = self.listeners.length - 1; k >= 0; k--) {
                var l = self.listeners[k];
                if (l.type == type && l.scope == scope && l.method == method) self.listeners.splice(k, 1);
            }
        };
        ${me}.lists.push(self);
        ${me}.hook();
    }

    static function hook() {
        if (${me}.hooked == true) return;
        ${me}.hooked = true;
        var mouse = new Object();
        mouse.onMouseWheel = function(delta) {
            ${me}.wheel(delta);
        };
        Mouse.addListener(mouse);
        var keys = new Object();
        keys.onKeyDown = function() {
            ${me}.key(Key.getCode());
        };
        Key.addListener(keys);
    }

    static function pick() {
        return ${me}.active != undefined ? ${me}.active : ${me}.lists[0];
    }

    // mouse wheel over a list: up = highlight moves up
    static function wheel(delta) {
        for (var k = 0; k < ${me}.lists.length; k++) {
            var l = ${me}.lists[k];
            if (l.under()) {
                l.move(delta > 0 ? -1 : 1);
                return;
            }
        }
    }

    // AS2 key events: used until the runtime forwards user events (input)
    static function key(code) {
        if (${me}.runtimeInput == true || ${me}.gated == true) return;
        var l = ${me}.pick();
        if (code == 38) l.move(-1);
        else if (code == 40) l.move(1);
        else if (code == 33) l.move(-l.full);
        else if (code == 34) l.move(l.full);
        else if (code == 13 || code == 69) l.accept();
    }

    // the runtime's user events (S7 On Input actions), called by the menu class
    // gated (the menu has a focus graph): only the list that has focus reacts. Returns true when the key was used; Up on the first and Down on the last item, Left and Right are not, so the menu class passes them to the focus graph.
    static function input(action, gated) {
        ${me}.runtimeInput = true;
        var l = gated == true ? ${me}.focused() : ${me}.pick();
        if (l == undefined) return false;
        if (action == "Up") return l.move(-1);
        if (action == "Down") return l.move(1);
        if (action == "PageUp") return l.move(-l.full);
        if (action == "PageDown") return l.move(l.full);
        if (action == "Accept") {
            l.accept();
            return true;
        }
        return false;
    }

    // the focus path is the list clip or one of its rows (a clicked row is a button)
    function owns(f) {
        var p = targetPath(this.clip);
        return f == p || f.substr(0, p.length + 1) == p + ".";
    }

    // the menu with a focus graph keeps the current member in focusPath (GFx's own focus can move on its own); without it the game's focus is used
    static function focused() {
        var f = ${me}.focusPath != undefined ? ${me}.focusPath : Selection.getFocus();
        for (var k = 0; k < ${me}.lists.length; k++) {
            if (${me}.lists[k].owns(f)) return ${me}.lists[k];
        }
        return undefined;
    }

    // the menu class calls this after every focus move of the focus graph: only the focused list shows its highlight, and a list that gains focus without one highlights its first item
    static function sync() {
        var f = ${me}.focusPath != undefined ? ${me}.focusPath : Selection.getFocus();
        for (var k = 0; k < ${me}.lists.length; k++) {
            var l = ${me}.lists[k];
            var h = l.owns(f);
            if (h == l.has) continue;
            l.has = h;
            if (h && l.hl < 0 && l.items.length > 0) l.highlight(0);
            else l.refresh();
        }
    }

    function under() {
        var x = this.clip._xmouse;
        var y = this.clip._ymouse;
        return this.clip._visible && x >= 0 && y >= 0 && x <= this.w && y <= this.h;
    }

    function setItems(items, owner) {
        if (owner != undefined) this.owner = owner;
        this.items = items instanceof Array ? items : [];
        this.hl = -1;
        this.clip.value = -1;
        this.top = 0;
        this.refresh();
    }

    function addItem(item, owner) {
        if (owner != undefined) this.owner = owner;
        if (item == undefined) return;
        this.items.push(item);
        this.refresh();
    }

    // a component list: row size from the first recipe (Make Component gives its design size), 40 when it has none
    function measure() {
        var s = this.items[0].size;
        this.tw = s != undefined ? s[0] : this.w;
        this.rowH = (s != undefined ? s[1] : 40) + this.spacing;
    }

    // a component row: (re)builds the component from its recipe only when the row shows another item
    function build(row, item) {
        if (row.built === item) return;
        row.built = item;
        row.body.removeMovieClip();
        if (typeof (item) != "object" || item.symbol == undefined) return;
        var b = row.attachMovie(item.symbol, "body", 1);
        b.tabEnabled = false;
        var c = item.cls;
        try {
            (new c(b, item.props == undefined ? {} : item.props, this.owner)).init();
        } catch (x) {
            trace("[Inkwell] list row: " + x);
        }
    }

    function move(d) {
        var n = this.items.length;
        if (n == 0) return false;
        if (this.hl >= 0 && (d == -1 || d == 1) && (this.hl + d < 0 || this.hl + d > n - 1)) return false;
        var i = this.hl < 0 ? (d > 0 ? d - 1 : 0) : this.hl + d;
        this.highlight(i);
        return true;
    }

    function highlight(i) {
        var n = this.items.length;
        if (n == 0) return;
        if (i < 0) i = 0;
        if (i > n - 1) i = n - 1;
        var changed = i != this.hl;
        this.hl = i;
        this.clip.value = i;
        this.refresh();
        if (changed) this.fire("change", {});
    }

    // clicks the first clip under mc that has an onRelease (the On Click of a button in a component row)
    function press(mc) {
        if (typeof (mc.onRelease) == "function") {
            mc.onRelease();
            return true;
        }
        for (var k in mc) {
            if (typeof (mc[k]) == "movieclip" && this.press(mc[k])) return true;
        }
        return false;
    }

    function accept() {
        if (this.hl >= 0 && this.hl < this.items.length) {
            this.fire("itemClick", { index: this.hl, data: this.items[this.hl] });
            if (this.comp) this.press(this.rows[this.hl - this.top].body);
        }
    }

    function click(i) {
        if (i < 0 || i >= this.items.length) return;
        ${me}.active = this;
        if (${me}.focusPath != undefined) ${me}.focusPath = targetPath(this.clip);
        this.highlight(i);
        this.fire("itemClick", { index: i, data: this.items[i] });
    }

    function fire(type, e) {
        e.type = type;
        e.target = this.clip;
        var ls = this.listeners.slice();
        for (var k = 0; k < ls.length; k++) {
            var l = ls[k];
            if (l.type != type) continue;
            try {
                l.scope[l.method](e);
            } catch (x) {
                trace("[Inkwell] list " + type + ": " + x);
            }
        }
    }

    function field(row, path) {
        var o = row;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) o = o[a[k]];
        return o;
    }

    function fill(row, item) {
        if (typeof (item) == "object") {
            for (var k = 0; k < this.names.length; k++) {
                var v = item[this.names[k]];
                this.field(row, this.paths[k]).text = v == undefined ? "" : String(v);
            }
        } else if (this.paths.length > 0) {
            this.field(row, this.paths[0]).text = item == undefined ? "" : String(item);
        }
    }

    function makeRow(r) {
        var self = this;
        if (this.comp) this.clip.createEmptyMovieClip("row" + r, 1000 + r);
        else this.tpl.duplicateMovieClip("row" + r, 1000 + r);
        var row = this.clip["row" + r];
        row.tabEnabled = false; // a row is not a focus target: the list is (GFx would move focus from one to the other by position)
        // a component row takes no mouse handler: a handler on the row would swallow the click and hover of the component inside (keys still use the list)
        if (this.comp) return row;
        var hit = row.createEmptyMovieClip("hit__", 9999);
        hit.beginFill(0, 0);
        hit.moveTo(0, 0);
        hit.lineTo(this.tw, 0);
        hit.lineTo(this.tw, this.rowH - this.spacing);
        hit.lineTo(0, this.rowH - this.spacing);
        hit.lineTo(0, 0);
        hit.endFill();
        row.onRelease = function() {
            self.click(this.itemIndex);
        };
        return row;
    }

    // redraws the rows from the current items: the visible rows plus one, recycled; the highlighted row is kept in view
    function refresh() {
        var n = this.items.length;
        if (this.comp && n > 0) this.measure();
        this.full = Math.max(1, Math.floor((this.h + this.spacing) / this.rowH));
        if (this.hl >= 0) {
            if (this.hl < this.top) this.top = this.hl;
            if (this.hl >= this.top + this.full) this.top = this.hl - this.full + 1;
        }
        var maxTop = Math.max(0, n - this.full);
        if (this.top > maxTop) this.top = maxTop;
        if (this.top < 0) this.top = 0;
        var pool = Math.ceil(this.h / this.rowH) + 1;
        for (var r = 0; r < pool; r++) {
            var i = this.top + r;
            var row = this.rows[r];
            if (i >= n) {
                if (row != undefined) row._visible = false;
                continue;
            }
            if (row == undefined) {
                row = this.makeRow(r);
                this.rows[r] = row;
            }
            row._visible = true;
            row._x = this.tx;
            row._y = this.ty + r * this.rowH;
            row.itemIndex = i;
            row._alpha = (i == this.hl && this.has != false) || i === this.hov ? 100 : 60;
            if (this.comp) this.build(row, this.items[i]);
            else this.fill(row, this.items[i]);
        }
        if (this.comp) this.light();
    }

    function hover() {
        var h;
        if (this.under()) {
            for (var r = 0; r < this.rows.length; r++) {
                var row = this.rows[r];
                if (row._visible && row.hitTest(_root._xmouse, _root._ymouse, false)) h = row.itemIndex;
            }
        }
        if (h === this.hov) return;
        this.hov = h;
        this.refresh();
    }

    // rows are not real focus targets, so the highlighted row's component gets its On Blur / On Focus here (only while the list has focus)
    function light() {
        var now = this.hl >= 0 && this.has != false ? this.items[this.hl] : undefined;
        if (now === this.lit) return;
        var old = this.lit;
        this.lit = now;
        for (var r = 0; r < this.rows.length; r++) {
            var row = this.rows[r];
            if (row.built === old && old != undefined) row.body.onKillFocus();
        }
        for (var r = 0; r < this.rows.length; r++) {
            var row = this.rows[r];
            if (row.built === now && now != undefined) row.body.onSetFocus();
        }
    }
}
`
}
