// The AS2 side of 9-slice / 3-slice images (PLAN-SLICING.md): a sliced image is a clip with the pieces `p0`..`p8` (row-major, a piece with an empty source is absent) and this
// helper repositions them when the clip's box changes. Plain `_width/_height` would stretch the corners too. The arithmetic is `shared/slice.ts` (a test runs this source against it).

export const sliceClassName = (modId: string): string => `mods.${modId}.InkwellSlice`

const q = (s: string): string => JSON.stringify(s)

/** Frame code that gives the clip at `path` (from `root`, no `root.` prefix) its slice record and lays the pieces out for its box. */
export const sliceMarkCode = (modId: string, root: string, path: string, s: { l: number; t: number; r: number; b: number; w: number; h: number }, bw: number, bh: number): string =>
  `${sliceClassName(modId)}.mark(${root}, ${q(path)}, ${[s.l, s.t, s.r, s.b, s.w, s.h, bw, bh].join(', ')});`

export function sliceClassSource(modId: string): string {
  return [
    '// Generated by Inkwell: 9-slice / 3-slice images. clip.inkwellSlice = {l, t, r, b, w, h, bw, bh} (insets and source size, current box); the pieces are clip.p0 .. clip.p8.',
    `class ${sliceClassName(modId)} {`,
    '    // [source start, source size, target start, target size] x 3; same arithmetic as shared/slice.ts sliceAxis',
    '    static function axis(a, b, src, box) {',
    '        var k = (a + b > box && a + b > 0) ? box / (a + b) : 1;',
    '        var da = a * k;',
    '        var db = b * k;',
    '        return [[0, a, 0, da], [a, src - a - b, da, box - da - db], [src - b, b, box - db, db]];',
    '    }',
    '',
    '    static function mark(root, path, l, t, r, b, w, h, bw, bh) {',
    '        try {',
    '            var c = root;',
    '            var a = path.split(".");',
    '            for (var i = 0; i < a.length; i++) c = c[a[i]];',
    '            if (c == undefined) return;',
    '            c.inkwellSlice = {l: l, t: t, r: r, b: b, w: w, h: h, bw: bw, bh: bh};',
    `            ${sliceClassName(modId)}.resize(c);`,
    '        } catch (e) {',
    '            trace("[Inkwell] slice " + path + ": " + e);',
    '        }',
    '    }',
    '',
    '    // w / h undefined = keep that side of the box',
    '    static function resize(c, w, h) {',
    '        var s = c.inkwellSlice;',
    '        if (s == undefined) return;',
    '        if (w != undefined) s.bw = w;',
    '        if (h != undefined) s.bh = h;',
    `        var xs = ${sliceClassName(modId)}.axis(s.l, s.r, s.w, s.bw);`,
    `        var ys = ${sliceClassName(modId)}.axis(s.t, s.b, s.h, s.bh);`,
    '        for (var r = 0; r < 3; r++) {',
    '            for (var q = 0; q < 3; q++) {',
    '                var p = c["p" + (r * 3 + q)];',
    '                if (p == undefined) continue;',
    '                var x = xs[q];',
    '                var y = ys[r];',
    '                p._visible = x[3] > 0 && y[3] > 0;',
    '                p._x = x[2];',
    '                p._y = y[2];',
    '                p._xscale = x[3] > 0 ? 100 * x[3] / x[1] : 0.1;',
    '                p._yscale = y[3] > 0 ? 100 * y[3] / y[1] : 0.1;',
    '            }',
    '        }',
    '    }',
    '}',
    ''
  ].join('\n')
}
