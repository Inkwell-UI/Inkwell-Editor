import type { Swf } from '@inkwell-ui/spec'

type Node = Swf['nodes'][string]
type Frame = Extract<Node, { type: 'frame' }>

/** What the compiler knows about one auto-layout frame that must re-lay out when a text of it changes; all numbers are design px relative to the frame. */
export interface FlowInfo {
  /** Clip path from the root timeline, `a.b.row` (the `root.` prefix is dropped). */
  path: string
  w: number
  h: number
  /** The frame sizes itself to its content along that axis (Figma Hug): `run` computes the size and keeps it in `inkwellW` / `inkwellH`. */
  hugW: boolean
  hugH: boolean
  /** 0 horizontal, 1 vertical. */
  mode: 0 | 1
  spacing: number
  /** Padding top, right, bottom, left. */
  pad: [number, number, number, number]
  /** Primary axis: 0 start, 1 center, 2 end, 3 space between. Counter axis: 0 start, 1 center, 2 end. */
  primary: number
  counter: number
  /** The children in the flow, in flow order. `hug`: 1 an auto-width text whose width is measured at run time, 2 a hugging frame whose size its own flow computed, 0 neither. `gx`/`gy`: the TextField gutter offset added to the box position. */
  items: { name: string; w: number; h: number; hug: 0 | 1 | 2; gx: number; gy: number }[]
}

export const flowClassName = (modId: string): string => `mods.${modId}.InkwellFlow`

const q = (s: string): string => JSON.stringify(s)
const num = (n: number): string => String(Math.round(n * 1000) / 1000)

/** Frame code that registers an auto-layout frame; runs before the graphs start. Nothing moves until a text of the frame changes (`touch`), so the design stays as Figma laid it out. */
export const flowAttachCode = (modId: string, f: FlowInfo, root = 'this'): string =>
  `${flowClassName(modId)}.attach(${root}, ${q(f.path)}, ${[f.w, f.h, f.hugW ? 1 : 0, f.hugH ? 1 : 0, f.mode, f.spacing, ...f.pad, f.primary, f.counter].map(num).join(', ')}, [${f.items.map((i) => q(i.name)).join(', ')}], [${f.items.map((i) => [i.w, i.h, i.hug, i.gx, i.gy].map(num).join(', ')).map((s) => `[${s}]`).join(', ')}]);`

/**
 * The auto-layout helper, generated by Inkwell: one class per mod. A frame registered with `attach` is laid out again by `touch(field)` after one of its texts changed
 * (Set Text, a translation): stack along the main axis with the spacing, padding and alignment Figma had, auto-width texts at their measured width. A frame that hugs its content
 * gets the size of its children plus padding (and its `fill` rectangle follows); the frame above it reads that size when its own `touch` turn comes.
 */
export function flowClassSource(modId: string): string {
  const me = flowClassName(modId)
  return `// Generated by Inkwell: the auto-layout helper. Do not edit.
class ${me} {
    static function attach(root, path, w, h, hugW, hugH, mode, spacing, pt, pr, pb, pl, primary, counter, names, items) {
        var clip = root;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) clip = clip[a[k]];
        if (clip == undefined) {
            trace("[Inkwell] flow " + path + ": clip not found");
            return;
        }
        clip.inkwellFlow = {w: w, h: h, hugW: hugW == 1, hugH: hugH == 1, mode: mode, spacing: spacing, pad: [pt, pr, pb, pl], primary: primary, counter: counter, names: names, items: items};
    }

    // Lays out every registered frame above the changed text field, innermost first.
    static function touch(field) {
        var c = field._parent;
        while (c != undefined) {
            if (c.inkwellFlow != undefined) ${me}.run(c);
            c = c._parent;
        }
    }

    static function run(clip) {
        var f = clip.inkwellFlow;
        var n = f.names.length;
        var vert = f.mode == 1;
        var sp = [];
        var sc = [];
        var sum = 0;
        for (var i = 0; i < n; i++) {
            var it = f.items[i];
            var w = it[0];
            var h = it[1];
            var m = clip[f.names[i]];
            if (it[2] == 1) w = m.textWidth;
            else if (it[2] == 2) {
                if (m.inkwellW != undefined) w = m.inkwellW;
                if (m.inkwellH != undefined) h = m.inkwellH;
            }
            sp[i] = vert ? h : w;
            sc[i] = vert ? w : h;
            sum += sp[i];
        }
        var padP0 = vert ? f.pad[0] : f.pad[3];
        var padP1 = vert ? f.pad[2] : f.pad[1];
        var padC0 = vert ? f.pad[3] : f.pad[0];
        var padC1 = vert ? f.pad[1] : f.pad[2];
        var hugP = vert ? f.hugH : f.hugW;
        var hugC = vert ? f.hugW : f.hugH;
        var innerP = (vert ? f.h : f.w) - padP0 - padP1;
        var innerC = (vert ? f.w : f.h) - padC0 - padC1;
        if (hugP) innerP = sum + f.spacing * (n - 1);
        if (hugC) {
            innerC = 0;
            for (var k = 0; k < n; k++) if (sc[k] > innerC) innerC = sc[k];
        }
        var gap = f.spacing;
        var pos = padP0;
        if (f.primary == 1) pos += (innerP - sum - gap * (n - 1)) / 2;
        else if (f.primary == 2) pos += innerP - sum - gap * (n - 1);
        else if (f.primary == 3 && n > 1) gap = (innerP - sum) / (n - 1);
        for (var j = 0; j < n; j++) {
            var cp = padC0;
            if (f.counter == 1) cp += (innerC - sc[j]) / 2;
            else if (f.counter == 2) cp += innerC - sc[j];
            var m = clip[f.names[j]];
            var g = f.items[j];
            m._x = (vert ? cp : pos) + g[3];
            m._y = (vert ? pos : cp) + g[4];
            pos += sp[j] + gap;
        }
        if (hugP || hugC) {
            var sizeP = innerP + padP0 + padP1;
            var sizeC = innerC + padC0 + padC1;
            var cw = vert ? sizeC : sizeP;
            var ch = vert ? sizeP : sizeC;
            if (f.hugW) {
                clip.inkwellW = cw;
                if (clip.fill != undefined) clip.fill._width = cw;
            }
            if (f.hugH) {
                clip.inkwellH = ch;
                if (clip.fill != undefined) clip.fill._height = ch;
            }
        }
    }
}
`
}

const PRIMARY: Record<string, number> = { MIN: 0, CENTER: 1, MAX: 2, SPACE_BETWEEN: 3, start: 0, center: 1, end: 2, spaceBetween: 3 }
const COUNTER: Record<string, number> = { MIN: 0, CENTER: 1, MAX: 2, BASELINE: 0, start: 0, center: 1, end: 2 }
const figmaOf = (n: Node): Record<string, unknown> => (n.extra?.['figma'] ?? {}) as Record<string, unknown>

/** Sizing of a node on one axis. A project synced before the Spec had `layout` keeps the Figma values under `extra.figma`. */
const sizingOf = (n: Node, axis: 'h' | 'v'): string => {
  const old = figmaOf(n)[axis === 'h' ? 'layoutSizingHorizontal' : 'layoutSizingVertical']
  return n.layout?.[axis] ?? (typeof old === 'string' ? old.toLowerCase() : 'fixed')
}
const isAbsolute = (n: Node): boolean => n.layout?.absolute === true || figmaOf(n)['layoutPositioning'] === 'ABSOLUTE'

/**
 * The flow of an auto-layout frame, or why it has none. Only frames with an auto-width text or a hugging frame of their own in the flow get one (nothing else changes size at
 * run time); a frame that wraps or holds a rotated child is left as designed (`skip`, for a lint note).
 */
export function flowInfo(
  n: Frame,
  nodes: Swf['nodes'],
  pathOf: (id: string) => string | undefined,
  gutterOf: (id: string) => { x: number; y: number } | undefined,
  /** A child frame that has a flow of its own: which axes it sizes itself on. */
  hugOf: (id: string) => { w: boolean; h: boolean } | undefined
): { info: FlowInfo } | { skip: string } | undefined {
  const a = n.autoLayout
  const here = pathOf(n.id)
  if (!a || !here) return undefined
  const fx = figmaOf(n)
  const kids = n.children.flatMap((id) => {
    const c = nodes[id]
    return c && pathOf(id) && !isAbsolute(c) ? [c] : []
  })
  if (!kids.some((c) => (c.type === 'text' && c.sizing === 'autoWidth') || hugOf(c.id))) return undefined
  if (a.wrap || fx['layoutWrap'] === 'WRAP') return { skip: 'it wraps' }
  if (kids.some((c) => c.transform.rotation !== 0)) return { skip: 'a child is rotated' }
  const info: FlowInfo = {
    path: here.slice('root.'.length), w: n.transform.width, h: n.transform.height, hugW: sizingOf(n, 'h') === 'hug', hugH: sizingOf(n, 'v') === 'hug', mode: a.mode === 'vertical' ? 1 : 0, spacing: a.spacing, pad: [a.padding[0]!, a.padding[1]!, a.padding[2]!, a.padding[3]!],
    primary: PRIMARY[String(fx['primaryAxisAlignItems'] ?? a.primaryAlign ?? 'start')] ?? 0,
    counter: COUNTER[String(fx['counterAxisAlignItems'] ?? a.counterAlign ?? 'start')] ?? 0,
    items: kids.map((c) => {
      const p = pathOf(c.id)!
      const g = c.type === 'text' ? gutterOf(c.id) : undefined
      return { name: p.slice(p.lastIndexOf('.') + 1), w: c.transform.width, h: c.transform.height, hug: c.type === 'text' && c.sizing === 'autoWidth' ? 1 : hugOf(c.id) ? 2 : 0, gx: g?.x ?? 0, gy: g?.y ?? 0 }
    })
  }
  return { info }
}
