/** A frame whose Figma overflow direction scrolls (SCROLL, docs/components.md): all numbers are design px relative to the frame. */
export interface ScrollInfo {
  /** Clip path from the root timeline, `a.b.frame` (the `root.` prefix is dropped). */
  path: string
  w: number
  h: number
  /** 1 = horizontal, 2 = vertical, 3 = both. */
  dir: number
  /** Padding after the content (right, bottom): the room that stays free when scrolled to the end. */
  padX: number
  padY: number
  /** Instance names of the layers inside the frame that move with the content (the frame's own fill and clip layer stay). */
  names: string[]
}

export const scrollClassName = (modId: string): string => `mods.${modId}.InkwellScroll`

const q = (s: string): string => JSON.stringify(s)
const num = (n: number): string => String(Math.round(n * 1000) / 1000)

/** Frame code that makes a compiled frame scrollable: runs before the menu class starts, so graphs can call `scrollTo` and `getScroll` on it. */
export const scrollAttachCode = (modId: string, s: ScrollInfo, root = 'this'): string =>
  `${scrollClassName(modId)}.attach(${root}, ${q(s.path)}, ${[s.w, s.h, s.dir, s.padX, s.padY].map(num).join(', ')}, [${s.names.map(q).join(', ')}]);`

/**
 * The scroll behaviour of frames that scroll in Figma, generated by Inkwell. The frame already clips (a clip layer); scrolling moves its content clips (the layers Figma designed, and the instances a graph
 * added, `clip.inkwellDyn`) by the offset, so a layer keeps its path and its own position. `attach` gives the frame clip `scrollTo(x, y)`, `scrollBy(dx, dy)` and `getScroll()` (`{x, y, maxX, maxY}`) for the
 * Scroll To and Get Scroll Position nodes, and keeps `inkwellOffX` / `inkwellOffY` for the instance layout (`stackMethods`). Input: mouse wheel over the frame, and Up, Down, PageUp, PageDown (Left, Right
 * for a horizontal one) from the AS2 `Key` listener until the runtime forwards user events to `input()` (the menu class does; then the key listener stops, so a key never scrolls twice).
 * In a preview build it traces `[Inkwell] bounds <clip path> <x> <y> <w> <h>` for the added instances after every move, like the instance layout does.
 * shortcut: a content layer moved by a later re-layout (text change in an auto-layout frame) loses its scroll offset until the next scroll; the offset is not eased.
 */
export function scrollClassSource(modId: string, preview = false): string {
  const me = scrollClassName(modId)
  return `// Generated by Inkwell: scrolling frames (Figma overflow direction). Do not edit.
class ${me} {
    static var all;
    static var hooked;
    static var runtimeInput;
    static var STEP = 40;
    var clip;
    var w;
    var h;
    var dir;
    var padX;
    var padY;
    var names;
    var offX;
    var offY;

    function InkwellScroll(clip, w, h, dir, padX, padY, names) {
        this.clip = clip;
        this.w = w;
        this.h = h;
        this.dir = dir;
        this.padX = padX;
        this.padY = padY;
        this.names = names;
        this.offX = 0;
        this.offY = 0;
    }

    // frame code: ${me}.attach(this, "path.to.frame", w, h, dir, padX, padY, [content layer names])
    static function attach(root, path, w, h, dir, padX, padY, names) {
        if (${me}.all == undefined) ${me}.all = [];
        var clip = root;
        var a = path.split(".");
        for (var k = 0; k < a.length; k++) clip = clip[a[k]];
        if (clip == undefined) {
            trace("[Inkwell] scroll " + path + ": clip not found");
            return;
        }
        for (var j = ${me}.all.length - 1; j >= 0; j--) if (${me}.all[j].clip == clip) ${me}.all.splice(j, 1);
        var self = new ${me}(clip, w, h, dir, padX, padY, names);
        clip.inkwellOffX = 0;
        clip.inkwellOffY = 0;
        clip.scrollTo = function(x, y) {
            self.to(x, y);
        };
        clip.scrollBy = function(dx, dy) {
            self.to(self.offX + dx, self.offY + dy);
        };
        clip.getScroll = function() {
            return self.state();
        };
        ${me}.all.push(self);
        ${me}.hook();
    }

    static function hook() {
        if (${me}.hooked == true) return;
        ${me}.hooked = true;
        var mouse = new Object();
        mouse.onMouseWheel = function(delta) {
            ${me}.wheel(delta);
        };
        Mouse.addListener(mouse);
        var keys = new Object();
        keys.onKeyDown = function() {
            ${me}.key(Key.getCode());
        };
        Key.addListener(keys);
    }

    // the frame under the mouse, else the first one that is shown
    static function pick() {
        var first;
        for (var k = ${me}.all.length - 1; k >= 0; k--) {
            var s = ${me}.all[k];
            if (!s.shown()) continue;
            if (s.under()) return s;
            first = s;
        }
        return first;
    }

    // mouse wheel over a frame: up = content moves down (offset shrinks); a frame that only scrolls sideways takes it too
    static function wheel(delta) {
        for (var k = ${me}.all.length - 1; k >= 0; k--) {
            var s = ${me}.all[k];
            if (!s.shown() || !s.under()) continue;
            var d = delta > 0 ? -${me}.STEP : ${me}.STEP;
            if (s.dir & 2) s.to(s.offX, s.offY + d);
            else s.to(s.offX + d, s.offY);
            return;
        }
    }

    static function key(code) {
        if (${me}.runtimeInput == true) return;
        ${me}.go(code == 38 ? "Up" : code == 40 ? "Down" : code == 33 ? "PageUp" : code == 34 ? "PageDown" : code == 37 ? "Left" : code == 39 ? "Right" : "");
    }

    // the runtime's user events (On Input actions), called by the menu class
    static function input(action) {
        ${me}.runtimeInput = true;
        ${me}.go(action);
    }

    static function go(action) {
        var s = ${me}.pick();
        if (s == undefined) return;
        var st = ${me}.STEP;
        if (action == "Up" && (s.dir & 2)) s.to(s.offX, s.offY - st);
        else if (action == "Down" && (s.dir & 2)) s.to(s.offX, s.offY + st);
        else if (action == "PageUp" && (s.dir & 2)) s.to(s.offX, s.offY - s.h);
        else if (action == "PageDown" && (s.dir & 2)) s.to(s.offX, s.offY + s.h);
        else if (action == "Left" && (s.dir & 1)) s.to(s.offX - st, s.offY);
        else if (action == "Right" && (s.dir & 1)) s.to(s.offX + st, s.offY);
    }

    function shown() {
        var c = this.clip;
        while (c != undefined && c != _root) {
            if (!c._visible) return false;
            c = c._parent;
        }
        return true;
    }

    function under() {
        var x = this.clip._xmouse;
        var y = this.clip._ymouse;
        return x >= 0 && y >= 0 && x <= this.w && y <= this.h;
    }

    // the content clips: the layers Figma designed, then the instances a graph added
    function kids() {
        var out = [];
        for (var k = 0; k < this.names.length; k++) {
            var c = this.clip[this.names[k]];
            if (c != undefined) out.push(c);
        }
        var dyn = this.clip.inkwellDyn;
        for (var j = 0; j < dyn.length; j++) if (dyn[j]._parent == this.clip) out.push(dyn[j]);
        return out;
    }

    function state() {
        var kids = this.kids();
        var right = 0;
        var bottom = 0;
        for (var k = 0; k < kids.length; k++) {
            var c = kids[k];
            if (!c._visible) continue;
            right = Math.max(right, c._x + this.offX + c._width);
            bottom = Math.max(bottom, c._y + this.offY + c._height);
        }
        return { x: this.offX, y: this.offY, maxX: Math.max(0, right + this.padX - this.w), maxY: Math.max(0, bottom + this.padY - this.h) };
    }

    // moves to the offset (design px from the start), kept between 0 and the end of the content, on the axes that scroll
    function to(x, y) {
        var s = this.state();
        var nx = this.offX;
        var ny = this.offY;
        if (this.dir & 1) nx = Math.max(0, Math.min(x, s.maxX));
        if (this.dir & 2) ny = Math.max(0, Math.min(y, s.maxY));
        var dx = nx - this.offX;
        var dy = ny - this.offY;
        this.offX = nx;
        this.offY = ny;
        this.clip.inkwellOffX = nx;
        this.clip.inkwellOffY = ny;
        if (dx == 0 && dy == 0) return;
        var kids = this.kids();
        for (var k = 0; k < kids.length; k++) {
            kids[k]._x -= dx;
            kids[k]._y -= dy;
        }${preview ? `
        var dyn = this.clip.inkwellDyn;
        for (var j = 0; j < dyn.length; j++) {
            var b = dyn[j].getBounds(_root);
            trace("[Inkwell] bounds " + dyn[j] + " " + b.xMin + " " + b.yMin + " " + (b.xMax - b.xMin) + " " + (b.yMax - b.yMin));
        }` : ''}
    }
}
`
}
