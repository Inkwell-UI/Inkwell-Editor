import { join } from 'node:path'
import { packVersion, parseVersion, RUNTIME_MESSAGES, RUNTIME_PLUGIN_NAME } from '@inkwell-ui/spec'
import type { LintIssue } from '../swf/lint'
import { buildPlayerAliasEsp } from '../widget/esp'
import { isPapyrusName, str, type PapyrusScript } from '../widget/papyrus'
import { compilePapyrus } from '../widget/papyrusCompiler'

// The missing/outdated runtime message of a custom-menu mod (SPEC-CHANGES S3 and O4, docs/menus.md "Runtime check"): a tiny master-less ESL plugin whose quest has a
// player alias, and one Papyrus script on that alias that asks SKSE for the Inkwell plugin's version. It must work WITHOUT Inkwell.dll, so it uses only vanilla and SKSE types.

export const runtimeCheckNames = (modId: string): { esp: string; script: string; quest: string; alias: string; pex: string; psc: string } => ({
  esp: `${modId}_RuntimeCheck.esp`, script: `${modId}_RuntimeCheck`, quest: `${modId}_RuntimeCheckQuest`, alias: 'InkwellRuntimeCheckPlayer',
  pex: `Scripts/${modId}_RuntimeCheck.pex`, psc: `Source/Scripts/${modId}_RuntimeCheck.psc`
})

// Placeholders the Spec's message functions are called with; the generated script splits their output on these, so the texts can only ever be the Spec's.
const NAME = '\u0001N', REQ = '\u0001R', MAJOR = 9999, HAVE = { major: 250, minor: 251, patch: 252 }
const TOKENS: Record<string, string> = { [NAME]: 'ModName', [REQ]: 'RequiredText', [String(MAJOR)]: 'RequiredMajor', '250.251.252': 'HaveText' }
const concat = (template: string): string =>
  template.split(/(\u0001N|\u0001R|9999|250\.251\.252)/).filter((p) => p !== '').map((p) => TOKENS[p] ?? str(p)).join(' + ')

/** Printable ASCII only (the compiler's source encoding is not guaranteed), no line breaks. */
const asciiName = (s: string, fallback: string): string => s.replace(/[^\x20-\x7e]+/g, '?').trim() || fallback

/** `<modId>_RuntimeCheck.psc`: `minRuntime` is the project's highest menu requirement (`MAJOR.MINOR.PATCH`). */
export function generateRuntimeCheckScript(o: { modId: string; modName: string; minRuntime: string }): PapyrusScript {
  if (!isPapyrusName(o.modId)) throw new Error(`The mod id "${o.modId}" is not a valid Papyrus name (ASCII letters and digits, starting with a letter).`)
  const v = parseVersion(o.minRuntime)
  if (!v) throw new Error(`"${o.minRuntime}" is not a runtime version (MAJOR.MINOR.PATCH).`)
  const name = runtimeCheckNames(o.modId).script
  const m = RUNTIME_MESSAGES
  const source = `Scriptname ${name} extends ReferenceAlias
{generated by Inkwell - do not edit; regenerate from the Inkwell project}

; Runtime check of "${asciiName(o.modName, o.modId).replace(/[\r\n]+/g, ' ')}" (SPEC-CHANGES S3). Needs only vanilla and SKSE: it works when ${RUNTIME_PLUGIN_NAME}.dll is missing.
; RequiredPacked is major * 16777216 + minor * 65536 + patch * 16, the form SKSE reports for a plugin version.
Int Property RequiredPacked = ${packVersion(v)} AutoReadOnly
Int Property RequiredMajor = ${v.major} AutoReadOnly
String Property RequiredText = ${str(o.minRuntime)} AutoReadOnly
String Property ModName = ${str(asciiName(o.modName, o.modId))} AutoReadOnly

Function Check()
	Int have = SKSE.GetPluginVersion(${str(RUNTIME_PLUGIN_NAME)})
	String haveText = ((have / 16777216) as String) + "." + (((have / 65536) % 256) as String) + "." + (((have / 16) % 4096) as String)
	If have <= 0
		Debug.Trace("[Inkwell] ${name}: the Inkwell runtime is not installed")
		Debug.MessageBox(${concat(m.notInstalled(NAME, REQ))})
	ElseIf have / 16777216 != RequiredMajor
		Debug.Trace("[Inkwell] ${name}: runtime " + haveText + " has another major version than " + RequiredText)
		Debug.MessageBox(${concat(m.majorMismatch(NAME, REQ, MAJOR, HAVE))})
	ElseIf have / 16 < RequiredPacked / 16
		Debug.Trace("[Inkwell] ${name}: runtime " + haveText + " is older than " + RequiredText)
		Debug.MessageBox(${concat(m.outdated(NAME, REQ, HAVE))})
	EndIf
EndFunction

; first time the alias is filled (new game, or the mod added to a save)
Event OnInit()
	Check()
EndEvent

; every load of a save
Event OnPlayerLoadGame()
	Check()
EndEvent
`
  return { name, source }
}

export interface RuntimeCheckResult {
  /** Mod-folder-relative path (forward slashes) -> bytes. Without a compiler: the source only (the .psc and no plugin, because a plugin without a script would do nothing). */
  files: Record<string, Buffer>
  lint: LintIssue[]
}

/** Source, compiled script and plugin of the runtime check. Compile errors come back as lint (`papyrus-compile-failed`); the plugin is only produced with a .pex. */
export async function compileRuntimeCheck(o: { modId: string; modName: string; minRuntime: string; papyrusExe: string; stubsDir?: string; buildDir: string }): Promise<RuntimeCheckResult> {
  const n = runtimeCheckNames(o.modId)
  const script = generateRuntimeCheckScript(o)
  const files: Record<string, Buffer> = { [n.psc]: Buffer.from(script.source) }
  const r = await compilePapyrus({ papyrusExe: o.papyrusExe, scripts: [script], workDir: join(o.buildDir, 'papyrus'), ...(o.stubsDir ? { stubsDir: o.stubsDir } : {}) })
  const pex = r.pex[script.name]
  if (pex && pex.length) {
    // the compiler stamps its compile time in the header (u64 at offset 8, big-endian); zeroing it makes deploys and packages byte-reproducible (nothing reads it in game)
    const stable = Buffer.from(pex)
    if (stable.readUInt32BE(0) === 0xfa57c0de) stable.fill(0, 8, 16)
    files[n.pex] = stable
    files[n.esp] = buildPlayerAliasEsp({ questEdid: n.quest, aliasName: n.alias, aliasScript: n.script })
  }
  return { files, lint: r.lint }
}
