import type { WidgetCall } from '../codegen/codegen'
import type { SettableText } from '../swf/generate'
import { QUEST_FORM_ID } from './esp'
import type { WidgetPlacement } from './frame'

export interface PapyrusScript {
  /** Script name = file name without `.psc`. */
  name: string
  source: string
}

/** Papyrus identifiers (and the file names derived from them): ASCII letters and digits, starting with a letter. */
export const isPapyrusName = (s: string): boolean => /^[A-Za-z][A-Za-z0-9]*$/.test(s)

const str = (s: string): string => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ')}"`
const flt = (n: number): string => (Number.isInteger(n) ? n.toFixed(1) : String(n))

export const widgetScriptName = (modId: string, widgetName: string): string => `${modId}_${widgetName}`
export const instanceScriptName = (modId: string, widgetName: string): string => `${modId}_${widgetName}Instance`
/** Path of the SWF relative to `Interface/exported/widgets/` (what `GetWidgetSource` returns). */
export const widgetSource = (modId: string, widgetName: string): string => `${modId}/${widgetName}.swf`

/** The widget script and its empty `...Instance` (SkyUI wants the attached script to differ from `GetWidgetType()`). Deterministic text. */
export function generateScripts(o: { modId: string; widgetName: string; displayName: string; placement: WidgetPlacement; texts?: readonly SettableText[]; debugHotkey?: number; calls?: readonly WidgetCall[] }): PapyrusScript[] {
  for (const [what, v] of [['modId', o.modId], ['widget name', o.widgetName]] as const)
    if (!isPapyrusName(v)) throw new Error(`The ${what} "${v}" is not a valid Papyrus name (ASCII letters and digits, starting with a letter).`)
  const name = widgetScriptName(o.modId, o.widgetName)
  const inst = instanceScriptName(o.modId, o.widgetName)
  const p = o.placement
  const calls = o.calls ?? []
  for (const c of calls) {
    if (!isPapyrusName(c.name) || RESERVED.has(c.name.toLowerCase())) throw new Error(`The On Widget Call name "${c.name}" cannot be a Papyrus function (ASCII letters and digits, starting with a letter; not one of ${[...RESERVED].join(', ')}).`)
    for (const q of c.params) if (!isPapyrusName(q.name)) throw new Error(`The parameter "${q.name}" of "${c.name}" is not a valid Papyrus name (ASCII letters and digits, starting with a letter).`)
  }
  const widget = `Scriptname ${name} extends SKI_WidgetBase
{generated by Inkwell - do not edit; regenerate from the Inkwell project}

; ---- generated by Inkwell: HUD widget "${o.displayName.replace(/[\r\n]+/g, ' ')}" ----

Event OnWidgetInit()
	WidgetName = ${str(o.displayName)}
	HAnchor = ${str(p.hAnchor)}
	VAnchor = ${str(p.vAnchor)}
	Debug.Trace("[Inkwell] ${name} OnWidgetInit")
EndEvent

; relative to Interface/exported/widgets/
string Function GetWidgetSource()
	return ${str(widgetSource(o.modId, o.widgetName))}
EndFunction

; must be this base script's name; the quest carries ${inst}
string Function GetWidgetType()
	return "${name}"
EndFunction

; position is the anchor point in SkyUI HUD space (1280x720), alpha in percent
Event OnWidgetReset()
	Parent.OnWidgetReset()
	X = ${flt(p.x)}
	Y = ${flt(p.y)}
	Alpha = ${flt(p.alpha)}
	Debug.Trace("[Inkwell] ${name} OnWidgetReset at " + X + "," + Y)
${calls.length ? graphReset(name, calls) : o.texts?.length ? popupReset(name) : ''}EndEvent
${calls.length ? graphApi(name, o.modId, calls, o.debugHotkey ?? 0) : o.texts?.length ? popupApi(name, o.modId, o.texts, o.debugHotkey ?? 0) : ''}`
  const instance = `Scriptname ${inst} extends ${name}
{generated by Inkwell - empty derived script; SkyUI requires the attached script to differ from GetWidgetType()}
`
  return [
    { name, source: widget },
    { name: inst, source: instance }
  ]
}

/** `asTitle` from instance name `title`: Bethesda's prefix keeps parameters clear of keywords and of SkyUI's members (Papyrus ignores case). */
export const paramName = (instanceName: string): string => `as${instanceName.charAt(0).toUpperCase()}${instanceName.slice(1)}`

// re-applies what was asked before the widget was ready (each game load recreates the SWF, hidden); (re)registers the debug hotkey
const popupReset = (name: string): string => `	UnregisterForAllKeys()
	If DebugHotkey > 0
		RegisterForKey(DebugHotkey)
		Debug.Trace("[Inkwell] ${name} debug hotkey " + DebugHotkey)
	EndIf
	If _hasTexts
		UI.InvokeStringA("HUD Menu", WidgetRoot + ".setTexts", _texts)
	EndIf
	If _pendingShow
		_pendingShow = False
		UI.InvokeFloat("HUD Menu", WidgetRoot + ".show", _pendingHold)
	EndIf
`

function popupApi(name: string, modId: string, texts: readonly SettableText[], hotkey: number): string {
  if (!Number.isInteger(hotkey) || hotkey < 0 || hotkey > 255) throw new Error(`The debug hotkey ${hotkey} is not a scan code (1..255, 0 = off).`)
  const sample = `${texts.map((_, i) => (i === 0 ? '"Inkwell test"' : `"Text ${i + 1}, shown by the ${name} test"`)).join(', ')}, 4.0`
  const params = texts.map((t) => `String ${paramName(t.name)}`).join(', ')
  const names = texts.map((t) => paramName(t.name)).join(', ')
  const layers = texts.map((t) => `;   ${paramName(t.name)}: layer "${t.layer.replace(/[\r\n]+/g, ' ')}" (node ${t.nodeId})`).join('\n')
  const fills = texts.map((t, i) => `	_texts[${i}] = ${paramName(t.name)}`).join('\n')
  return `
; ---- popup API: settable texts (overlay role "text"), in layer order ----
${layers}
; Safe before the widget is ready: the call is remembered and applied in OnWidgetReset.

String[] _texts
Bool _hasTexts = False
Bool _pendingShow = False
Float _pendingHold = 4.0

; test hotkey: a DirectInput scan code (65 = F7), 0 = off. Set per project in the Inkwell overlay (debugHotkey); keep 0 for a release.
Int Property DebugHotkey = ${hotkey} Auto

; sets the texts without changing visibility
Function SetTexts(${params})
	_texts = new String[${texts.length}]
${fills}
	_hasTexts = True
	If Ready
		UI.InvokeStringA("HUD Menu", WidgetRoot + ".setTexts", _texts)
	EndIf
EndFunction

; sets the texts, fades in (0.3 s), holds afHoldSeconds, fades out; afHoldSeconds <= 0 stays until Hide(). A Show while visible restarts the hold.
Function Show(${params}, Float afHoldSeconds = 4.0)
	SetTexts(${names})
	If Ready
		UI.InvokeFloat("HUD Menu", WidgetRoot + ".show", afHoldSeconds)
	Else
		_pendingShow = True
		_pendingHold = afHoldSeconds
	EndIf
EndFunction

; fades out from the current alpha
Function Hide()
	_pendingShow = False
	If Ready
		UI.InvokeFloat("HUD Menu", WidgetRoot + ".hide", 0.0)
	EndIf
EndFunction

; SKSE key event; only while playing (not in the console or a menu)
Event OnKeyDown(Int aiKeyCode)
	If DebugHotkey > 0 && aiKeyCode == DebugHotkey && !Utility.IsInMenuMode()
		Debug.Trace("[Inkwell] ${name} debug hotkey: Show")
		Show(${sample})
	EndIf
EndEvent

; test helper for other scripts: ${name}.Test()
Function Test() global
	; ${(QUEST_FORM_ID & 0xffffff)} = local form id 0x${(QUEST_FORM_ID & 0xffffff).toString(16)} of the quest in the ESL-flagged plugin
	${name} w = Game.GetFormFromFile(${QUEST_FORM_ID & 0xffffff}, "${modId}.esp") as ${name}
	If w
		Debug.Trace("[Inkwell] ${name}.Test: Show")
		w.Show(${sample})
	Else
		Debug.Trace("[Inkwell] ${name}.Test: quest not found in ${modId}.esp")
	EndIf
EndFunction
`
}

/** Names a generated function must not take: the test helper, the key event, and SKI_WidgetBase's own members that scripts of ours override or read. */
const RESERVED = new Set(['test', 'onkeydown', 'onwidgetinit', 'onwidgetreset', 'ready', 'x', 'y', 'alpha', 'getwidgetsource', 'getwidgettype'])

// a call made before the widget was ready is remembered (the last one only) and replayed once here, as the 0.1 popup did
const graphReset = (name: string, calls: readonly WidgetCall[]): string => `	UnregisterForAllKeys()
	If DebugHotkey > 0
		RegisterForKey(DebugHotkey)
		Debug.Trace("[Inkwell] ${name} debug hotkey " + DebugHotkey)
	EndIf
	If _pendingCall != ""
		String c = _pendingCall
		_pendingCall = ""
		Debug.Trace("[Inkwell] ${name} replaying the call made before the widget was ready: " + c)
${calls.map((c, k) => `		${k ? 'ElseIf' : 'If'} c == "${c.name}"
			${c.params.length ? `UI.InvokeStringA("HUD Menu", WidgetRoot + ".${c.name}", _pendingArgs)` : `UI.InvokeBool("HUD Menu", WidgetRoot + ".${c.name}", True)`}`).join('\n')}
		EndIf
	EndIf
`

/** One entry: the hotkey calls it. Several: each press runs the next step (an entry with a Bool parameter gets two steps, False then True), so one key tests every entry. */
function hotkeyEvent(name: string, calls: readonly WidgetCall[], first: WidgetCall, sample: (c: WidgetCall, flag?: boolean) => string): string {
  const steps = calls.flatMap((c) => (c.params.some((p) => p.type === 'Bool') ? [{ c, flag: false }, { c, flag: true }] : [{ c, flag: true }]))
  const head = `; SKSE key event; only while playing (not in the console or a menu)
Event OnKeyDown(Int aiKeyCode)
	If DebugHotkey > 0 && aiKeyCode == DebugHotkey && !Utility.IsInMenuMode()
`
  if (steps.length === 1) return `${head}		Debug.Trace("[Inkwell] ${name} debug hotkey: ${first.name}")
		${first.name}(${sample(first)})
	EndIf
EndEvent
`
  return `; each press of the debug hotkey runs the next step: ${steps.map((x) => `${x.c.name}(${sample(x.c, x.flag)})`.replace(/"/g, "'")).join(', ')}, then again
Int _debugStep = 0

${head}		Int s = _debugStep
		_debugStep = (s + 1) % ${steps.length}
${steps.map((x, k) => `		${k ? 'ElseIf' : 'If'} s == ${k}
			Debug.Trace("[Inkwell] ${name} debug hotkey: ${x.c.name}(${sample(x.c, x.flag).replace(/"/g, "'")})")
			${x.c.name}(${sample(x.c, x.flag)})`).join('\n')}
		EndIf
	EndIf
EndEvent
`
}

const PREFIX = { String: 'as', Number: 'af', Bool: 'ab' } as const
const PTYPE = { String: 'String', Number: 'Float', Bool: 'Bool' } as const
const pname = (type: keyof typeof PREFIX, n: string): string => `${PREFIX[type]}${n.charAt(0).toUpperCase()}${n.slice(1)}`

/**
 * Papyrus API from the graphs' On Widget Call entries: one function per entry with the typed parameters. UI.Invoke* cannot mix types, so the
 * arguments travel as one String[] (Numbers and Bools as text) and the generated clip method converts them back (codegen.ts). No parameters:
 * UI.InvokeBool. A call before the widget is ready is remembered (the last one only) and replayed once in OnWidgetReset.
 */
function graphApi(name: string, modId: string, calls: readonly WidgetCall[], hotkey: number): string {
  if (!Number.isInteger(hotkey) || hotkey < 0 || hotkey > 255) throw new Error(`The debug hotkey ${hotkey} is not a scan code (1..255, 0 = off).`)
  const sample = (c: WidgetCall, flag = true): string => c.params.map((p, i) => (p.type === 'String' ? (i === 0 ? '"Inkwell test"' : `"Text ${i + 1}, shown by the ${name} test"`) : p.type === 'Number' ? '4.0' : flag ? 'True' : 'False')).join(', ')
  const fns = calls.map((c) => {
    const params = c.params.map((p) => `${PTYPE[p.type]} ${pname(p.type, p.name)}`).join(', ')
    const fills = c.params.map((p, i) => {
      const v = pname(p.type, p.name)
      return p.type === 'String' ? `	a[${i}] = ${v}` : p.type === 'Number' ? `	a[${i}] = ${v} as String` : `	If ${v}
		a[${i}] = "true"
	Else
		a[${i}] = "false"
	EndIf`
    })
    const call = c.params.length
      ? `		UI.InvokeStringA("HUD Menu", WidgetRoot + ".${c.name}", a)`
      : `		UI.InvokeBool("HUD Menu", WidgetRoot + ".${c.name}", True)`
    return `
; generated from the graph's On Widget Call "${c.name}"
Function ${c.name}(${params})
${c.params.length ? `	String[] a = new String[${c.params.length}]\n${fills.join('\n')}\n` : ''}	If Ready
${call}
	Else
		_pendingCall = "${c.name}"
${c.params.length ? '		_pendingArgs = a\n' : ''}		Debug.Trace("[Inkwell] ${name}.${c.name}: the widget is not ready; remembered, replayed on reset")
	EndIf
EndFunction
`
  })
  const first = calls[0]!
  return `
; ---- widget API: the On Widget Call entries of the project's graphs ----
; Int Property DebugHotkey: a DirectInput scan code (65 = F7), 0 = off. Set per project in the Inkwell overlay (debugHotkey); keep 0 for a release.
Int Property DebugHotkey = ${hotkey} Auto

; the last call made before the widget was ready, replayed once in OnWidgetReset
String _pendingCall = ""
String[] _pendingArgs
${fns.join('')}
${hotkeyEvent(name, calls, first, sample)}
; test helper for other scripts: ${name}.Test()
Function Test() global
	; ${QUEST_FORM_ID & 0xffffff} = local form id 0x${(QUEST_FORM_ID & 0xffffff).toString(16)} of the quest in the ESL-flagged plugin
	${name} w = Game.GetFormFromFile(${QUEST_FORM_ID & 0xffffff}, "${modId}.esp") as ${name}
	If w
		Debug.Trace("[Inkwell] ${name}.Test: ${first.name}")
		w.${first.name}(${sample(first)})
	Else
		Debug.Trace("[Inkwell] ${name}.Test: quest not found in ${modId}.esp")
	EndIf
EndFunction
`
}
