import type { WidgetPlacement } from './frame'

export interface PapyrusScript {
  /** Script name = file name without `.psc`. */
  name: string
  source: string
}

/** Papyrus identifiers (and the file names derived from them): ASCII letters and digits, starting with a letter. */
export const isPapyrusName = (s: string): boolean => /^[A-Za-z][A-Za-z0-9]*$/.test(s)

const str = (s: string): string => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ')}"`
const flt = (n: number): string => (Number.isInteger(n) ? n.toFixed(1) : String(n))

export const widgetScriptName = (modId: string, widgetName: string): string => `${modId}_${widgetName}`
export const instanceScriptName = (modId: string, widgetName: string): string => `${modId}_${widgetName}Instance`
/** Path of the SWF relative to `Interface/exported/widgets/` (what `GetWidgetSource` returns). */
export const widgetSource = (modId: string, widgetName: string): string => `${modId}/${widgetName}.swf`

/** The widget script and its empty `...Instance` (SkyUI wants the attached script to differ from `GetWidgetType()`). Deterministic text. */
export function generateScripts(o: { modId: string; widgetName: string; displayName: string; placement: WidgetPlacement }): PapyrusScript[] {
  for (const [what, v] of [['modId', o.modId], ['widget name', o.widgetName]] as const)
    if (!isPapyrusName(v)) throw new Error(`The ${what} "${v}" is not a valid Papyrus name (ASCII letters and digits, starting with a letter).`)
  const name = widgetScriptName(o.modId, o.widgetName)
  const inst = instanceScriptName(o.modId, o.widgetName)
  const p = o.placement
  const widget = `Scriptname ${name} extends SKI_WidgetBase
{generated by Inkwell - do not edit; regenerate from the Inkwell project}

; ---- generated by Inkwell: HUD widget "${o.displayName.replace(/[\r\n]+/g, ' ')}" ----

Event OnWidgetInit()
	WidgetName = ${str(o.displayName)}
	HAnchor = ${str(p.hAnchor)}
	VAnchor = ${str(p.vAnchor)}
	Debug.Trace("[Inkwell] ${name} OnWidgetInit")
EndEvent

; relative to Interface/exported/widgets/
string Function GetWidgetSource()
	return ${str(widgetSource(o.modId, o.widgetName))}
EndFunction

; must be this base script's name; the quest carries ${inst}
string Function GetWidgetType()
	return "${name}"
EndFunction

; position is the anchor point in SkyUI HUD space (1280x720), alpha in percent
Event OnWidgetReset()
	Parent.OnWidgetReset()
	X = ${flt(p.x)}
	Y = ${flt(p.y)}
	Alpha = ${flt(p.alpha)}
	Debug.Trace("[Inkwell] ${name} OnWidgetReset at " + X + "," + Y)
EndEvent
`
  const instance = `Scriptname ${inst} extends ${name}
{generated by Inkwell - empty derived script; SkyUI requires the attached script to differ from GetWidgetType()}
`
  return [
    { name, source: widget },
    { name: inst, source: instance }
  ]
}
