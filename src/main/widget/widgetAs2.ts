import type { SettableText } from '../swf/generate'

/** Methods SkyUI calls on the `widget` clip (via UI.Invoke* on `_root.WidgetContainer.<id>.widget`); names are the contract, the bodies are original. */
export const CONTRACT_METHODS = [
  'setHudMetrics', 'setRootPath', 'setClientInfo', 'setModes', 'onModeChange',
  'setHAnchor', 'setVAnchor', 'setPositionX', 'setPositionY', 'setAlpha'
] as const

/**
 * AS2 class `mods.<modId>.<cls>` whose `install(w)` gives the clip `w` the SkyUI widget contract.
 * Proven shape (0.0 spike, SkyUI 5.2 and 6.11): positions arrive in HUD space (0..1280 x 0..720 on 16:9) and are mapped onto
 * -hMin..hMax / -vMin..vMax (hMin/vMin = the safe-rect origin), the anchor shifts the holder clip (the widget's parent) by the
 * widget's own size: X/Y is the anchored edge, as in SkyUI's own WidgetBase. Until 2026-10-24 the lerp ran backwards (target and
 * source swapped), which moved every widget by twice the safe-rect inset (about +33/+34 HUD px, measured in game).
 */
export function widgetContractClass(modId: string, cls: string, texts: readonly SettableText[] = []): string {
  const popup = texts.length > 0
  return `// Generated by Inkwell: the SkyUI widget contract for the root clip "widget". Do not edit.
class mods.${modId}.${cls} {
    static function install(w) {
        w._hAnchor = "left";
        w._vAnchor = "top";
        w._px = 0;
        w._py = 0;
        w.log = function (s) {
            try {
                if (typeof (_global.skse) == "object" && _global.skse.Log != undefined) {
                    _global.skse.Log("[Inkwell] " + s);
                }
            } catch (e) {
            }
        };
        // lerp(targetMin, targetMax, sourceMin, sourceMax, v): v in source -> target, SkyUI's argument order (Shared.GlobalFunc.Lerp)
        w.lerp = function (a, b, c, d, v) {
            return a + (v - c) / (d - c) * (b - a);
        };
        // HUD position (0..1280 x 0..720) -> the container's space (-hMin..hMax, it sits at the safe-rect origin), then shift the holder for the anchor (left/top = 0, right/bottom = -size, center = -size/2)
        w.updatePosition = function () {
            var m = this._hudMetrics;
            var h = this._parent;
            var x = this._px;
            var y = this._py;
            if (m != undefined) {
                x = this.lerp(-m.hMin, m.hMax, 0, 1280, x);
                y = this.lerp(-m.vMin, m.vMax, 0, 720, y);
            }
            h._x = this._hAnchor == "right" ? -this._width : (this._hAnchor == "center" ? -this._width / 2 : 0);
            h._y = this._vAnchor == "bottom" ? -this._height : (this._vAnchor == "center" ? -this._height / 2 : 0);
            this._x = x;
            this._y = y;
        };
        w.setHudMetrics = function (m) { this._hudMetrics = m; this.log("setHudMetrics"); };
        w.setRootPath = function (p) { this._rootPath = p; this.log("setRootPath " + p); };
        w.setClientInfo = function (s) { this._clientInfo = s; };
        w.setModes = function () { this._parent._visible = true; this.log("setModes"); };
        w.onModeChange = function (m) { this._mode = m; };
        w.setHAnchor = function (a) { this._hAnchor = a.toLowerCase(); this.updatePosition(); };
        w.setVAnchor = function (a) { this._vAnchor = a.toLowerCase(); this.updatePosition(); };
        w.setPositionX = function (v) { this._px = v; this.updatePosition(); };
        w.setPositionY = function (v) { this._py = v; this.updatePosition(); };
${popup ? `        w.setAlpha = function (a) { this._baseAlpha = a; this.applyFade(); };\n${popupMethods(texts)}` : '        w.setAlpha = function (a) { this._alpha = a; };\n'}    }
}
`
}

const FADE_MS = 300
const comment = (s: string): string => s.replace(/[\r\n]+/g, ' ')
const lit = (s: string): string => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ')

/**
 * Popup behaviour of a widget with settable texts (overlay role "text"): starts hidden; setTexts(a, b, ...) in layer order; show(holdSeconds)
 * fades in (0.3 s), holds, fades out (hold <= 0: stays until hide()); hide() fades out from the current alpha. A show() while visible restarts
 * the hold without a jump. Time comes from getTimer(), so the frame rate does not matter. The fade multiplies SkyUI's alpha (setAlpha).
 * Each settable field keeps its Figma box (autoSize off) and shrinks long text to fit (GFx textAutoSize, verified in game); the layout class
 * still applies the IR's own textFit after this.
 */
function popupMethods(texts: readonly SettableText[]): string {
  const args = texts.map((_, i) => `a${i}`).join(', ')
  const fields = texts.flatMap((t) => [`        // node ${comment(t.nodeId)} "${comment(t.layer)}"`, `        w.initText(w.${t.path}, "${lit(t.nodeId)}");`])
  const sets = texts.flatMap((t, i) => [
    `            // node ${comment(t.nodeId)} "${comment(t.layer)}"`,
    `            try {`,
    `                this.${t.path}.text = a${i} == undefined ? "" : String(a${i});`,
    `            } catch (e) {`,
    `                this.log("node ${lit(t.nodeId)}: " + e);`,
    `            }`
  ])
  return [
    '        // ---- popup: settable texts, show/hide with a fade ----',
    '        _global.gfxExtensions = true;',
    '        w._baseAlpha = 100;',
    '        w._fade = 0;',
    `        w._fadeMs = ${FADE_MS};`,
    '        w._inStart = 0;',
    '        w._outStart = -1;',
    '        w._visible = false;',
    '        w._alpha = 0;',
    '        w.initText = function (t, id) {',
    '            try {',
    '                t.autoSize = "none";',
    '                t.textAutoSize = "shrink";',
    '            } catch (e) {',
    '                this.log("node " + id + ": " + e);',
    '            }',
    '        };',
    ...fields,
    `        w.setTexts = function (${args}) {`,
    ...sets,
    '        };',
    '        w.applyFade = function () {',
    '            this._alpha = this._baseAlpha * this._fade;',
    '            this._visible = this._fade > 0;',
    '        };',
    '        // fade in from the current alpha, then hold; _outStart < 0 = no fade out',
    '        w.show = function (hold) {',
    '            try {',
    '                var s = Number(hold);',
    '                if (isNaN(s)) s = 4;',
    '                this._inStart = getTimer() - this._fade * this._fadeMs;',
    '                this._outStart = s > 0 ? this._inStart + this._fadeMs + s * 1000 : -1;',
    '                this.startTween();',
    '            } catch (e) {',
    '                this.log("show: " + e);',
    '            }',
    '        };',
    '        // fade out from the current alpha',
    '        w.hide = function () {',
    '            try {',
    '                this._outStart = getTimer() - (1 - this._fade) * this._fadeMs;',
    '                this._inStart = this._outStart - this._fadeMs;',
    '                this.startTween();',
    '            } catch (e) {',
    '                this.log("hide: " + e);',
    '            }',
    '        };',
    '        w.startTween = function () {',
    '            this.onEnterFrame = function () {',
    '                try {',
    '                    this.tick();',
    '                } catch (e) {',
    '                    delete this.onEnterFrame;',
    '                    this.log("tick: " + e);',
    '                }',
    '            };',
    '            this.tick();',
    '        };',
    '        w.tick = function () {',
    '            var now = getTimer();',
    '            var out = this._outStart >= 0 && now >= this._outStart;',
    '            var f = out ? 1 - (now - this._outStart) / this._fadeMs : (now - this._inStart) / this._fadeMs;',
    '            f = f < 0 ? 0 : (f > 1 ? 1 : f);',
    '            this._fade = f;',
    '            this.applyFade();',
    '            if ((out && f == 0) || (!out && f == 1 && this._outStart < 0)) {',
    '                delete this.onEnterFrame;',
    '            }',
    '        };',
    ''
  ].join('\n')
}
