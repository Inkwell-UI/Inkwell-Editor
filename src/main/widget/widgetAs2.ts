/** Methods SkyUI calls on the `widget` clip (via UI.Invoke* on `_root.WidgetContainer.<id>.widget`); names are the contract, the bodies are original. */
export const CONTRACT_METHODS = [
  'setHudMetrics', 'setRootPath', 'setClientInfo', 'setModes', 'onModeChange',
  'setHAnchor', 'setVAnchor', 'setPositionX', 'setPositionY', 'setAlpha'
] as const

/**
 * AS2 class `mods.<modId>.<cls>` whose `install(w)` gives the clip `w` the SkyUI widget contract.
 * Proven shape (0.0 spike, SkyUI 5.2 and 6.11): positions arrive in HUD space (hMin..hMax, 0..1280 x 0..720 on 16:9),
 * the anchor shifts the holder clip (the widget's parent) by the widget's own size.
 */
export function widgetContractClass(modId: string, cls: string): string {
  return `// Generated by Inkwell: the SkyUI widget contract for the root clip "widget". Do not edit.
class mods.${modId}.${cls} {
    static function install(w) {
        w._hAnchor = "left";
        w._vAnchor = "top";
        w._px = 0;
        w._py = 0;
        w.log = function (s) {
            try {
                if (typeof (_global.skse) == "object" && _global.skse.Log != undefined) {
                    _global.skse.Log("[Inkwell] " + s);
                }
            } catch (e) {
            }
        };
        w.lerp = function (a, b, c, d, v) {
            return c + (d - c) * (v - a) / (b - a);
        };
        // HUD-space position -> screen, then shift the holder for the anchor (left/top = 0, right/bottom = -size, center = -size/2)
        w.updatePosition = function () {
            var m = this._hudMetrics;
            var h = this._parent;
            var x = this._px;
            var y = this._py;
            if (m != undefined) {
                x = this.lerp(-m.hMin, m.hMax, 0, 1280, x);
                y = this.lerp(-m.vMin, m.vMax, 0, 720, y);
            }
            h._x = this._hAnchor == "right" ? -this._width : (this._hAnchor == "center" ? -this._width / 2 : 0);
            h._y = this._vAnchor == "bottom" ? -this._height : (this._vAnchor == "center" ? -this._height / 2 : 0);
            this._x = x;
            this._y = y;
        };
        w.setHudMetrics = function (m) { this._hudMetrics = m; this.log("setHudMetrics"); };
        w.setRootPath = function (p) { this._rootPath = p; this.log("setRootPath " + p); };
        w.setClientInfo = function (s) { this._clientInfo = s; };
        w.setModes = function () { this._parent._visible = true; this.log("setModes"); };
        w.onModeChange = function (m) { this._mode = m; };
        w.setHAnchor = function (a) { this._hAnchor = a.toLowerCase(); this.updatePosition(); };
        w.setVAnchor = function (a) { this._vAnchor = a.toLowerCase(); this.updatePosition(); };
        w.setPositionX = function (v) { this._px = v; this.updatePosition(); };
        w.setPositionY = function (v) { this._py = v; this.updatePosition(); };
        w.setAlpha = function (a) { this._alpha = a; };
    }
}
`
}
